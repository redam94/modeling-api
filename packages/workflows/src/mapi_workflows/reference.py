"""The workflow node reference, generated from the node catalog (Markdown for the docs).

``python -m mapi_workflows.reference > docs/reference/workflow-nodes.md`` regenerates the
page; a test fails when the committed page drifts from the catalog
(:data:`mapi_spec.workflow_nodes.NODE_IMPLEMENTATIONS`). Every entry shows the node's About
card (plain language first), its ports, parameters with defaults and the result fields that
branch conditions may read.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Mapping
from typing import Any

from mapi_spec.workflow_nodes import (
    NODE_IMPLEMENTATIONS,
    NODE_KIND_ABOUTS,
    NodeImplementation,
    NodeKind,
)

__all__ = ["main", "node_reference"]

_RUNS_IN = {
    "orchestrator": "the orchestrator (no data; computed from earlier results)",
    "sandbox": "a sandboxed `workflow_node` run",
    "child_run": "its own child run (a `fit` run for `model.fit`, else a `workflow_node` run)",
}


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _param_rows(schema: Mapping[str, Any]) -> list[str]:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    rows = []
    for name, sub in props.items():
        if not isinstance(sub, Mapping):
            continue
        typ = sub.get("type")
        if "enum" in sub:
            typ = " \\| ".join(f"`{v}`" for v in sub["enum"])
        elif isinstance(typ, list):
            typ = " or ".join(str(t) for t in typ)
        elif typ is None and "anyOf" in sub:
            typ = "see schema"
        default = (
            f"`{json.dumps(sub['default'])}`"
            if "default" in sub
            else ("**required**" if name in required else "")
        )
        desc = sub.get("description") or ""
        rows.append(f"| `{name}` | {_cell(typ or 'object')} | {default} | {_cell(desc)} |")
    return rows


def _node(impl: NodeImplementation) -> list[str]:
    a = impl.about
    out = [
        f"### `{impl.id}` — {a.title}",
        "",
        a.summary_plain,
        "",
        f"*Runs in* {_RUNS_IN[impl.runs_in]}. *Difficulty:* {a.difficulty.value}. "
        f"*Typical runtime:* {a.typical_runtime.value}."
        + (
            ""
            if impl.cacheable
            else " *Never cached* (its result depends on more than its inputs)."
        ),
        "",
    ]
    if a.use_when:
        out += ["**Use it when:** " + "; ".join(a.use_when) + ".", ""]
    if a.avoid_when:
        out += ["**Avoid it when:** " + "; ".join(a.avoid_when) + ".", ""]
    if a.example:
        out += [f"**Example:** {a.example}", ""]
    if impl.inputs:
        out.append(
            "**Inputs:** "
            + ", ".join(
                f"`{p}` ({s.type.value}{', several' if s.multiple else ''}"
                f"{', optional' if not s.required else ''})"
                for p, s in impl.inputs.items()
            )
            + "."
        )
        out.append("")
    if impl.outputs:
        out.append(
            "**Outputs:** " + ", ".join(f"`{p}` ({t.value})" for p, t in impl.outputs.items()) + "."
        )
    out.append("")
    rows = _param_rows(impl.params_schema)
    if rows:
        out += ["| Parameter | Type | Default | Meaning |", "|---|---|---|---|", *rows, ""]
    if impl.result_fields:
        fields = ", ".join(f"`{k}` ({f.type})" for k, f in impl.result_fields.items())
        out += [f"Result fields (`nodes.<id>.<field>` in conditions): {fields}.", ""]
    if a.expert_notes:
        out += [f'??? note "Expert detail"\n    {a.expert_notes}', ""]
    return out


def node_reference() -> str:
    """The Markdown reference page."""
    out = [
        "# Workflow node reference",
        "",
        "<!-- Generated by `python -m mapi_workflows.reference`; do not edit by hand. -->",
        "",
        "Every node a workflow can use, grouped by kind. Each entry starts with the plain "
        "description the web app shows on the node's About card. See the "
        "[workflows guide](../guides/workflows.md) for how to wire nodes together.",
        "",
    ]
    for kind in NodeKind:
        impls = sorted(
            (i for i in NODE_IMPLEMENTATIONS.values() if i.kind is kind), key=lambda i: i.id
        )
        if not impls:
            continue
        about = NODE_KIND_ABOUTS.get(kind)
        out += [f"## {about.title if about else kind.value.title()} (`{kind.value}`)", ""]
        if about is not None:
            out += [about.summary_plain, ""]
        for impl in impls:
            out += _node(impl)
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    sys.stdout.write(node_reference())


if __name__ == "__main__":  # pragma: no cover
    main()
