# =================================================================================== signatures


def generate_webhook_secret() -> str:
    """A new secret: ``whsec_`` + 32 random bytes, base64url without padding."""
    raw = secrets.token_urlsafe(32)
    return "whsec_" + raw[:43]


def sign_payload(body: bytes, secret: str, timestamp: int) -> str:
    """The hex HMAC-SHA256 of ``"<timestamp>.<body>"`` under ``secret``."""
    msg = str(int(timestamp)).encode("ascii") + b"." + body
    return hmac.new(secret.encode("utf-8"), msg, hashlib.sha256).hexdigest()


def signature_header(body: bytes, secrets_: Sequence[str], timestamp: int | None = None) -> str:
    """``t=<unix>,v1=<hex>[,v1=<hex>…]`` - one ``v1`` per active secret (rotation)."""
    if not secrets_:
        raise ValueError("at least one secret is needed")
    t = int(time.time()) if timestamp is None else int(timestamp)
    return ",".join([f"t={t}", *(f"v1={sign_payload(body, s, t)}" for s in secrets_)])


_HEX64 = re.compile(r"^[0-9a-f]{64}$")


def parse_signature_header(header: str) -> tuple[int, list[str]]:
    """``(timestamp, [v1 signatures])``; unknown schemes are ignored. ``ValueError`` if
    malformed (no or several ``t``, a bad ``v1``, no ``v1`` at all, over 4 KB)."""
    if len(header) > 4096:
        raise ValueError("signature header too long")
    t: int | None = None
    sigs: list[str] = []
    for part in header.split(","):
        key, sep, value = part.strip().partition("=")
        if not sep:
            raise ValueError("malformed signature header")
        if key == "t":
            if t is not None or not value.isdigit() or len(value) > 12:
                raise ValueError("malformed timestamp")
            t = int(value)
        elif key == "v1":
            if not _HEX64.match(value):
                raise ValueError("malformed v1 signature")
            sigs.append(value)
    if t is None or not sigs:
        raise ValueError("the header needs t= and at least one v1=")
    return t, sigs


def check_signature(
    body: bytes,
    header: str | None,
    secrets_: str | Iterable[str],
    *,
    now: int | None = None,
    tolerance: int = SIGNATURE_TOLERANCE_S,
) -> int:
    """Verify a delivery; return its timestamp or raise ``WEBHOOK_SIGNATURE_INVALID``.

    Accepts if *any* ``v1`` matches *any* of ``secrets_`` (constant-time comparison) and the
    timestamp is within ``tolerance`` seconds of ``now`` (either direction).
    """
    if not header:
        raise MapiError(
            f"missing {SIGNATURE_HEADER} header", code=ErrorCode.WEBHOOK_SIGNATURE_INVALID
        )
    try:
        t, sigs = parse_signature_header(header)
    except ValueError as exc:
        raise MapiError(str(exc), code=ErrorCode.WEBHOOK_SIGNATURE_INVALID) from None
    current = int(time.time()) if now is None else int(now)
    if abs(current - t) > tolerance:
        raise MapiError(
            "the signature timestamp is outside the tolerance",
            code=ErrorCode.WEBHOOK_SIGNATURE_INVALID,
        )
    keys = [secrets_] if isinstance(secrets_, str) else list(secrets_)
    ok = False
    for key in keys:
        expected = sign_payload(body, key, t)
        for sig in sigs:
            ok |= hmac.compare_digest(expected, sig)
    if not ok:
        raise MapiError("no signature matches", code=ErrorCode.WEBHOOK_SIGNATURE_INVALID)
    return t


def verify_signature(
    body: bytes,
    header: str | None,
    secrets_: str | Iterable[str],
    *,
    now: int | None = None,
    tolerance: int = SIGNATURE_TOLERANCE_S,
) -> bool:
    """:func:`check_signature` as a boolean (for receivers)."""
    try:
        check_signature(body, header, secrets_, now=now, tolerance=tolerance)
    except MapiError:
        return False
    return True


# ====================================================================================== retries

RETRY_SCHEDULE: Final[tuple[timedelta, ...]] = (
    timedelta(minutes=1),
    timedelta(minutes=5),
    timedelta(minutes=30),
    timedelta(hours=2),
    timedelta(hours=6),
    timedelta(hours=12),
    timedelta(hours=24),
)
"""Delay before retry *n* (after attempt *n*); 8 attempts over about 45 hours."""
AUTO_DISABLE_AFTER: Final = 20
"""A webhook is disabled after this many consecutive events failed (or at once on 410)."""


def next_retry_delay(
    attempt: int, response_code: int | None = None, *, jitter: float = 0.0
) -> timedelta | None:
    """The delay before the next try after ``attempt`` failed, or ``None`` to give up.

    2xx is success (no retry); 410 Gone never retries; ``jitter`` in ``[0, 1)`` adds up to
    10% (callers pass a random number; tests pass a fixed one).
    """
    if response_code is not None and 200 <= response_code < 300:
        return None
    if response_code == 410 or attempt < 1 or attempt > len(RETRY_SCHEDULE):
        return None
    if not 0 <= jitter < 1:
        raise ValueError("jitter must be in [0, 1)")
    base = RETRY_SCHEDULE[attempt - 1]
    return base + base * (0.1 * jitter)


