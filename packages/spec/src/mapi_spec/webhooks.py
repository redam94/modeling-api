"""Outgoing webhooks: events, envelope, signatures, deliveries and the SSRF policy
(plan §8.2 Integrations, §9 "Webhook SSRF"; M3).

**Events** (:class:`WebhookEventType`) are delivered as a JSON :class:`WebhookEnvelope`::

    {"id": "evt_…", "type": "run.succeeded", "created": "2026-10-15T09:30:00Z",
     "tenant": "acme", "project": "growth", "api_version": "v1", "data": {...}}

**Signatures.** Every delivery carries ``Mapi-Signature: t=<unix seconds>,v1=<hex>`` where
``v1`` is HMAC-SHA256 under the webhook secret of ``"<t>.<raw body>"``. While a secret is
being rotated the header carries one ``v1`` per active secret. Receivers verify with
:func:`verify_signature` and refuse timestamps more than :data:`SIGNATURE_TOLERANCE_S`
(300 s) away from their clock, which bounds replays.

**SSRF.** The server delivers only under :data:`SSRF_POLICY`: ``https`` only, allowed
ports, no credentials in URLs, blocked internal host names; it resolves the host *itself*,
refuses if **any** address is private, loopback, link-local, metadata, CGNAT, ULA,
multicast or otherwise non-global (:func:`ip_is_blocked`, including IPv4 embedded in IPv6),
connects to the pinned address it checked (SNI and ``Host`` keep the name), follows no
redirects, gives up after 5 s and reads at most 256 KiB of the response.
"""

