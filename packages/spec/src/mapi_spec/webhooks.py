@dataclass(frozen=True, slots=True)
class SsrfPolicy:
    """How the server delivers webhooks (data, so docs and tests read the same values)."""

    schemes: tuple[str, ...] = ("https",)
    ports: tuple[int, ...] = (443, 8443)
    blocked_networks: tuple[ipaddress.IPv4Network | ipaddress.IPv6Network, ...] = _BLOCKED_NETS
    blocked_hosts: frozenset[str] = frozenset(
        {"localhost", "metadata", "metadata.google.internal", "instance-data"}
    )
    blocked_suffixes: tuple[str, ...] = (
        ".localhost",
        ".local",
        ".internal",
        ".intranet",
        ".lan",
        ".home.arpa",
        ".corp",
    )
    resolve_then_check: bool = True
    """Resolve the host first and check *every* address it resolves to."""
    pin_resolved_ip: bool = True
    """Connect to the checked address (no second resolution: no DNS rebinding)."""
    follow_redirects: bool = False
    timeout_s: float = 5.0
    max_response_bytes: int = 256 * 1024
    max_url_length: int = 2048
    user_agent: str = "mapi-webhooks/1"
    allow_ip_literals: bool = False
    """URLs naming an IP address directly are refused (public or not)."""


SSRF_POLICY: Final = SsrfPolicy()


def ip_is_blocked(
    address: str | ipaddress.IPv4Address | ipaddress.IPv6Address, policy: SsrfPolicy = SSRF_POLICY
) -> bool:
    """Is ``address`` unsafe to connect to? Covers every non-global range and IPv4 embedded
    in IPv6 (mapped ``::ffff:a.b.c.d``, NAT64 ``64:ff9b::/96``, 6to4 ``2002::/16``)."""
    try:
        ip = ipaddress.ip_address(address) if isinstance(address, str) else address
    except ValueError:
        return True
    if isinstance(ip, ipaddress.IPv6Address):
        embedded = ip.ipv4_mapped or ip.sixtofour
        if embedded is None and ip in ipaddress.ip_network("64:ff9b::/96"):
            embedded = ipaddress.IPv4Address(int(ip) & 0xFFFFFFFF)
        if embedded is not None and ip_is_blocked(embedded, policy):
            return True
        if ip.scope_id:
            return True
    if any(ip in net for net in policy.blocked_networks if net.version == ip.version):
        return True
    return not ip.is_global or ip.is_multicast or ip.is_reserved


def _blocked(reason: str) -> MapiError:
    return MapiError(reason, code=ErrorCode.WEBHOOK_URL_BLOCKED, pointer="/url")


def check_webhook_url(url: str, policy: SsrfPolicy = SSRF_POLICY) -> str:
    """Static checks of a webhook URL (before any DNS). Returns the lower-cased host.

    Raises ``WEBHOOK_URL_BLOCKED`` for: another scheme, credentials, a fragment, a port
    outside ``policy.ports``, an IP literal, a blocked host name or suffix, a single-label
    host, or characters outside a plain DNS name.
    """
    if len(url) > policy.max_url_length or any(c.isspace() or ord(c) < 32 for c in url):
        raise _blocked("the URL is too long or contains spaces or control characters")
    try:
        parts = urlsplit(url)
        port = parts.port
    except ValueError:
        raise _blocked("the URL cannot be parsed") from None
    if parts.scheme.lower() not in policy.schemes:
        raise _blocked(f"webhook URLs must use {' or '.join(policy.schemes)}")
    if parts.username is not None or parts.password is not None or "@" in parts.netloc:
        raise _blocked("webhook URLs cannot contain credentials")
    if parts.fragment:
        raise _blocked("webhook URLs cannot contain a fragment")
    host = (parts.hostname or "").rstrip(".").lower()
    if not host:
        raise _blocked("the URL has no host")
    if (port or 443) not in policy.ports:
        raise _blocked(f"webhook URLs may use ports {', '.join(map(str, policy.ports))} only")
    try:
        ipaddress.ip_address(host.strip("[]"))
    except ValueError:
        pass
    else:
        raise _blocked("webhook URLs must name a host, not an IP address")
    if not re.fullmatch(r"(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z][a-z0-9-]{0,62}", host):
        raise _blocked("the host is not a fully qualified DNS name")
    if host in policy.blocked_hosts or host.endswith(policy.blocked_suffixes):
        raise _blocked("the host is internal")
    if re.fullmatch(r"[0-9.]+|0x[0-9a-f.x]+", host):
        raise _blocked("numeric host names are not allowed")
    return host


def check_resolved_addresses(addresses: Sequence[str], policy: SsrfPolicy = SSRF_POLICY) -> str:
    """After resolution: every address must be allowed; return the one to pin (the first).

    Raises ``WEBHOOK_URL_BLOCKED`` when there is none or any is blocked (a host with one
    private and one public address is refused: DNS answers can rotate).
    """
    if not addresses:
        raise _blocked("the host did not resolve")
    for a in addresses:
        if ip_is_blocked(a, policy):
            raise _blocked("the host resolves to a private or reserved address")
    return addresses[0]
