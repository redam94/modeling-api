__all__ = ["WebhookCreate", "WebhookUpdate", "router"]

router = APIRouter(prefix="/v1/webhooks", tags=["webhooks"])

WebhookId = Annotated[
    str, Path(pattern=r"^whk_[0-9a-z]{26}$", examples=["whk_01jaf3h1j2k3m4n5p6q7r8s9t0"])
]
DeliveryId = Annotated[str, Path(pattern=r"^whd_[0-9a-z]{26}$")]


def _resolver(ctx: ServerContext) -> Resolver:
    return ctx.webhook_resolver or SystemResolver()


class WebhookCreate(_SpecWebhookCreate):
    """``POST /v1/webhooks``: the secret is generated by the server and shown once.

    The server applies the SSRF policy to ``url`` (static checks, then every address the
    host resolves to): ``422 WEBHOOK_URL_BLOCKED``. ``https`` only, ports 443 and 8443.
    """

    @field_validator("url")
    @classmethod
    def _url(cls, v: str) -> str:  # the scheme is the server policy's (dev allows http)
        return v


class WebhookUpdate(_SpecWebhookUpdate):
    """``PATCH /v1/webhooks/{webhook_id}`` (re-activating resets the failure count)."""

    @field_validator("url")
    @classmethod
    def _url(cls, v: str | None) -> str | None:
        return v


def _box(ctx: ServerContext) -> SecretBox:
    return SecretBox(ctx.secrets.webhook_key)


async def _audit(
    ctx: ServerContext,
    session: AsyncSession | None,
    action: AuditAction,
    resource_id: str | None,
    *,
    outcome: AuditOutcome = AuditOutcome.SUCCESS,
    code: ErrorCode | None = None,
    details: dict[str, JsonValue] | None = None,
) -> None:
    if ctx.request is None:
        return
    ev = ctx.request.audit(
        ctx,
        action,
        ResourceKind.WEBHOOK,
        outcome,
        resource_id=resource_id,
        code=code,
        details=details,
    )
    await write_audit(ctx.db, [ev], session=session)


async def _check_url(ctx: ServerContext, url: str, stage: str, resource_id: str | None) -> None:
    """The SSRF policy now (static checks + resolution); refusals are audited."""
    policy = UrlPolicy.from_settings(ctx.settings)
    try:
        try:
            await policy.resolve(url, _resolver(ctx))
        except ResolutionFailed as exc:
            raise blocked(f"{exc}: check the host name") from None
    except MapiError as exc:
        obs_metrics.record_webhook_blocked(stage)
        await _audit(
            ctx,
            None,
            AuditAction.WEBHOOK_URL_BLOCKED,
            resource_id,
            outcome=AuditOutcome.DENIED,
            code=ErrorCode.WEBHOOK_URL_BLOCKED,
            details={"stage": stage, "host": describe_host(url), "reason": exc.detail[:300]},
        )
        raise


async def _load(session: AsyncSession, ctx: ServerContext, webhook_id: str) -> m.Webhook:
    row = await session.get(m.Webhook, webhook_id, with_for_update=True)
    if row is None or (row.tenant_id, row.project_id) != (
        ctx.scope.tenant_id,
        ctx.scope.project_id,
    ):
        raise NotFoundError("webhook", webhook_id)
    return row


@router.get(
    "",
    response_model=Page[Webhook],
    operation_id="list_webhooks",
    summary="Webhooks of the project",
    responses=responses_for("list_webhooks"),
)
async def list_webhooks(
    ctx: Ctx, session: Session, limit: Limit = DEFAULT_LIMIT, cursor: str | None = None
) -> Page[Webhook]:
    stmt = select(m.Webhook).where(
        m.Webhook.tenant_id == ctx.scope.tenant_id, m.Webhook.project_id == ctx.scope.project_id
    )
    after = decode_cursor(cursor)
    if after is not None:
        stmt = stmt.where(m.Webhook.id < str(after))
    rows = list(
        (await session.execute(stmt.order_by(m.Webhook.id.desc()).limit(limit + 1))).scalars()
    )
    more = len(rows) > limit
    rows = rows[:limit]
    return Page[Webhook](
        items=[webhook_dto(r) for r in rows],
        next_cursor=encode_cursor(rows[-1].id) if more and rows else None,
    )


@router.post(
    "",
    response_model=WebhookCreated,
    status_code=status.HTTP_201_CREATED,
    operation_id="create_webhook",
    summary="Add a webhook (the secret is shown once)",
    responses=responses_for("create_webhook", extra=problem_responses(ErrorCode.CONFLICT)),
)
async def create_webhook(ctx: Ctx, session: Session, body: WebhookCreate) -> JSONResponse:
    """Subscribe ``url`` to ``events`` of this project. The answer holds the signing secret
    (``whsec_…``) - the only time it is returned; deliveries are signed with it
    (``Mapi-Signature: t=…,v1=…``). At most ``MAPI_WEBHOOK_MAX_PER_PROJECT`` webhooks per
    project (``409 CONFLICT``)."""
    await _check_url(ctx, body.url, "create", None)
    count = (
        await session.execute(
            select(func.count()).where(
                m.Webhook.tenant_id == ctx.scope.tenant_id,
                m.Webhook.project_id == ctx.scope.project_id,
            )
        )
    ).scalar_one()
    if count >= ctx.settings.webhook_max_per_project:
        raise Conflict(
            f"the project already has {count} webhooks (the limit is "
            f"{ctx.settings.webhook_max_per_project}); delete one first"
        )
    row, secret = new_webhook(
        _box(ctx),
        tenant_id=ctx.scope.tenant_id,
        project_id=ctx.scope.project_id,
        url=body.url,
        events=list(body.events),
        description=body.description,
        active=body.active,
        created_by=ctx.request.principal_id if ctx.request else None,
    )
    session.add(row)
    await session.flush()
    await _audit(
        ctx,
        session,
        AuditAction.WEBHOOK_CREATE,
        row.id,
        details={
            "host": describe_host(row.url),
            "events": [str(e) for e in row.events],
            "active": row.active,
        },
    )
    created = WebhookCreated(webhook=webhook_dto(row), secret=secret)
    return JSONResponse(created.model_dump(mode="json"), status_code=status.HTTP_201_CREATED)


@router.get(
    "/{webhook_id}",
    response_model=Webhook,
    operation_id="get_webhook",
    summary="A webhook (never its secret)",
    responses=responses_for("get_webhook"),
)
async def get_webhook(ctx: Ctx, session: Session, webhook_id: WebhookId) -> Webhook:
    return webhook_dto(await _load(session, ctx, webhook_id))


@router.patch(
    "/{webhook_id}",
    response_model=Webhook,
    operation_id="update_webhook",
    summary="Change URL, events or active",
    responses=responses_for("update_webhook"),
)
async def update_webhook(
    ctx: Ctx, session: Session, webhook_id: WebhookId, body: WebhookUpdate
) -> Webhook:
    """Re-activating a webhook (``active: true``) resets its consecutive-failure count and
    clears the reason it was disabled for."""
    row = await _load(session, ctx, webhook_id)
    changed: list[JsonValue] = []
    if body.url is not None and body.url != row.url:
        await _check_url(ctx, body.url, "update", row.id)
        row.url = body.url
        changed.append("url")
    if body.events is not None:
        row.events = [e.value for e in body.events]
        changed.append("events")
    if "description" in body.model_fields_set:
        row.description = body.description
        changed.append("description")
    if body.active is not None and body.active != row.active:
        row.active = body.active
        changed.append("active")
        if body.active:
            row.failure_count = 0
            row.disabled_reason = None
    row.updated_at = now()
    await _audit(
        ctx,
        session,
        AuditAction.WEBHOOK_UPDATE,
        row.id,
        details={"changed": changed, "host": describe_host(row.url), "active": row.active},
    )
    return webhook_dto(row)


@router.delete(
    "/{webhook_id}",
    status_code=status.HTTP_204_NO_CONTENT,
    operation_id="delete_webhook",
    summary="Delete a webhook and its delivery log",
    responses=responses_for("delete_webhook"),
)
async def delete_webhook(ctx: Ctx, session: Session, webhook_id: WebhookId) -> Response:
    row = await _load(session, ctx, webhook_id)
    await _audit(
        ctx,
        session,
        AuditAction.WEBHOOK_DELETE,
        row.id,
        details={"host": describe_host(row.url)},
    )
    await session.delete(row)
    return Response(status_code=status.HTTP_204_NO_CONTENT)


@router.post(
    "/{webhook_id}:rotate-secret",
    response_model=WebhookCreated,
    operation_id="rotate_webhook_secret",
    summary="New secret (shown once); the old one signs too for 24 h",
    responses=responses_for("rotate_webhook_secret"),
)
async def rotate_webhook_secret(
    ctx: Ctx, session: Session, webhook_id: WebhookId
) -> WebhookCreated:
    """While the previous secret is still valid, deliveries carry two ``v1`` signatures."""
    row = await _load(session, ctx, webhook_id)
    out = rotate_secret(_box(ctx), row)
    await _audit(
        ctx,
        session,
        AuditAction.WEBHOOK_SECRET_ROTATE,
        row.id,
        details={"secret_hint": row.secret_hint},
    )
    return out


@router.get(
    "/{webhook_id}/deliveries",
    response_model=Page[WebhookDelivery],
    operation_id="list_webhook_deliveries",
    summary="Delivery log, newest first (filter: status)",
    responses=responses_for("list_webhook_deliveries"),
)
async def list_webhook_deliveries(
    ctx: Ctx,
    session: Session,
    webhook_id: WebhookId,
    limit: Limit = DEFAULT_LIMIT,
    cursor: str | None = None,
    status_: Annotated[DeliveryStatus | None, Query(alias="status")] = None,
) -> Page[WebhookDelivery]:
    """``response_excerpt`` is the start of the receiver's answer: untrusted text."""
    row = await _load(session, ctx, webhook_id)
    stmt = select(m.WebhookDelivery).where(m.WebhookDelivery.webhook_id == row.id)
    if status_ is not None:
        stmt = stmt.where(m.WebhookDelivery.status == status_.value)
    after = decode_cursor(cursor)
    if after is not None:
        stmt = stmt.where(m.WebhookDelivery.id < str(after))
    rows = list(
        (
            await session.execute(stmt.order_by(m.WebhookDelivery.id.desc()).limit(limit + 1))
        ).scalars()
    )
    more = len(rows) > limit
    rows = rows[:limit]
    return Page[WebhookDelivery](
        items=[delivery_dto(r) for r in rows],
        next_cursor=encode_cursor(rows[-1].id) if more and rows else None,
    )


@router.post(
    "/{webhook_id}/deliveries/{delivery_id}:replay",
    response_model=WebhookDelivery,
    status_code=status.HTTP_202_ACCEPTED,
    operation_id="replay_webhook_delivery",
    summary="Send an event again (a new delivery, replay_of set)",
    responses=responses_for("replay_webhook_delivery", extra=problem_responses(ErrorCode.CONFLICT)),
)
async def replay_webhook_delivery(
    ctx: Ctx, session: Session, webhook_id: WebhookId, delivery_id: DeliveryId
) -> JSONResponse:
    """A new delivery of the same event (same event id, so receivers can deduplicate), sent
    by the worker within seconds; the webhook must be active."""
    row = await _load(session, ctx, webhook_id)
    original = await session.get(m.WebhookDelivery, delivery_id)
    if original is None or original.webhook_id != row.id:
        raise NotFoundError("delivery", delivery_id)
    if not row.active:
        raise Conflict("the webhook is not active; re-activate it before replaying")
    await _check_url(ctx, row.url, "replay", row.id)
    new = replay_delivery(original)
    session.add(new)
    await session.flush()
    await _audit(
        ctx,
        session,
        AuditAction.WEBHOOK_REPLAY,
        row.id,
        details={"delivery_id": new.id, "replay_of": original.id, "event_id": original.event_id},
    )
    return JSONResponse(
        delivery_dto(new).model_dump(mode="json"), status_code=status.HTTP_202_ACCEPTED
    )
