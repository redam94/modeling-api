"""Static catalog export: ``python -m mapi_steps.catalog [--splits] [--out FILE]``.

Prints the :class:`mapi_spec.catalog.Catalog` JSON of every built-in step (settings JSON
Schema, templated SchemaEffect, context need, kind, flags). Runner images generate it at
build time; the control plane loads it to validate specs without importing step code.
``--splits`` adds the split catalog under a separate ``splits`` key (not part of
``Catalog``). The same JSON ships with the package as ``mapi_steps/catalog.json``.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from importlib import resources
from pathlib import Path
from typing import Any

from mapi_spec.catalog import Catalog

__all__ = ["catalog", "catalog_json", "main", "shipped_catalog"]


def catalog() -> Catalog:
    """The built-in step catalog."""
    from mapi_steps import registry

    return registry().catalog()


def catalog_json(*, splits: bool = False, indent: int | None = 2) -> str:
    """Deterministic JSON text of the catalog (optionally with the split catalog)."""
    from mapi_steps.splits import split_catalog

    doc: dict[str, Any] = catalog().model_dump(mode="json", exclude_defaults=True)
    if splits:
        doc["splits"] = [e.model_dump(mode="json") for e in split_catalog()]
    return json.dumps(doc, indent=indent, sort_keys=True) + "\n"


def shipped_catalog() -> Catalog:
    """The catalog JSON shipped inside the package (regenerated by the build)."""
    text = resources.files("mapi_steps").joinpath("catalog.json").read_text("utf-8")
    data = json.loads(text)
    data.pop("splits", None)
    return Catalog.model_validate(data)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m mapi_steps.catalog", description=__doc__)
    parser.add_argument("--splits", action="store_true", help="include the split catalog")
    parser.add_argument("--out", type=Path, help="write to this file instead of stdout")
    args = parser.parse_args(argv)
    text = catalog_json(splits=args.splits)
    if args.out is not None:
        args.out.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
