def _metric_rows() -> Iterator[tuple[str, str, tuple[str, ...], str]]:
    from mapi_server.observability.metrics import Metrics
    from prometheus_client.metrics import MetricWrapperBase

    metrics = Metrics()
    for value in vars(metrics).values():
        if not isinstance(value, MetricWrapperBase):
            continue
        kind = str(value._type)
        name = value._name + ("_total" if kind == "counter" else "")
        yield name, kind, tuple(value._labelnames), value._documentation


def metrics_table() -> str:
    lines = ["| Metric | Type | Labels | Meaning |", "|---|---|---|---|"]
    for name, kind, labels, doc in _metric_rows():
        label = ", ".join(f"`{x}`" for x in labels) or "—"
        lines.append(f"| `{name}` | {kind} | {label} | {_cell(doc)} |")
    return "\n".join(lines) + "\n"


def _yaml(path: Path) -> Any:
    import yaml

    return yaml.safe_load(path.read_text("utf-8"))


_TEMPLATE = re.compile(r"\{\{\s*(.*?)\s*\}\}")


def _untemplate(text: str) -> str:
    """An alert summary without Go templating: ``$labels.x`` -> ``<x>``, values -> ``N``."""

    def repl(m: re.Match[str]) -> str:
        expr = m.group(1)
        if expr.startswith("$labels."):
            return f"<{expr.removeprefix('$labels.').split()[0]}>"
        return "N %" if "humanizePercentage" in expr else "N"

    return _TEMPLATE.sub(repl, text)


def alerts_table() -> str:
    doc = _yaml(ROOT / "ops" / "alerts" / "prometheus-rules.yml")
    lines = ["| Alert | Severity | Fires when | Says | Runbook |", "|---|---|---|---|---|"]
    for group in doc.get("groups", []):
        for rule in group.get("rules", []):
            if "alert" not in rule:
                continue
            notes = rule.get("annotations", {})
            summary = _untemplate(notes.get("summary", "")).strip()
            expr = " ".join(str(rule.get("expr", "")).split())
            hold = rule.get("for", "0m")
            when = f"`{_cell(expr)}`" + (f" for {hold}" if hold not in ("0m", "0s") else "")
            runbook = notes.get("runbook", "")
            book = f"`{runbook}`" if runbook else "—"
            sev = rule.get("labels", {}).get("severity", "")
            lines.append(f"| `{rule['alert']}` | {sev} | {when} | {_cell(summary)} | {book} |")
    return "\n".join(lines) + "\n"


def dashboards_table() -> str:
    lines = ["| File | Dashboard | Sections |", "|---|---|---|"]
    for path in sorted((ROOT / "ops" / "dashboards").glob("*.json")):
        data = json.loads(path.read_text("utf-8"))
        rel = path.relative_to(ROOT).as_posix()
        if "panels" in data:  # Grafana
            rows = [p["title"] for p in data["panels"] if p.get("type") == "row"]
            n = sum(1 for p in data["panels"] if p.get("type") != "row")
            lines.append(
                f"| `{rel}` | Grafana: {_cell(data.get('title', ''))} "
                f"| {n} panels in {len(rows)} rows: {_cell(', '.join(rows))} |"
            )
        else:  # Cloud Monitoring
            tiles = data.get("mosaicLayout", {}).get("tiles", [])
            titles = [t.get("widget", {}).get("title", "") for t in tiles]
            lines.append(
                f"| `{rel}` | Cloud Monitoring: {_cell(data.get('displayName', ''))} "
                f"| {len(tiles)} tiles: {_cell(', '.join(t for t in titles if t))} |"
            )
    return "\n".join(lines) + "\n"


def runbooks_table() -> str:
    lines = ["| Runbook | For | Starts with |", "|---|---|---|"]
    for path in sorted((ROOT / "ops" / "runbooks").glob("*.md")):
        text = path.read_text("utf-8")
        title = next((ln[2:] for ln in text.splitlines() if ln.startswith("# ")), path.stem)
        title = title.removeprefix("Runbook: ").strip()
        body = text.split("\n", 1)[1] if "\n" in text else ""
        para = next((p for p in body.strip().split("\n\n") if p.strip()), "")
        first = re.split(r"(?<=\.)\s", " ".join(para.split()), maxsplit=1)[0]
        rel = path.relative_to(ROOT).as_posix()
        lines.append(f"| `{rel}` | {_cell(title)} | {_cell(first)} |")
    return "\n".join(lines) + "\n"


