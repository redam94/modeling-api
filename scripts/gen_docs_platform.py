    ("infra/", "Terraform"),
    ("deploy/", "deploy scripts"),
    ("scripts/dev.py", "`make dev`"),
    ("scripts/docs_", "documentation tooling"),
    ("scripts/", "repository scripts"),
    ("security/", "security suite"),
    ("ops/", "dashboards and alerts"),
