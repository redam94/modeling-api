def _source_files() -> Iterator[Path]:
    for name in SCAN_FILES:
        if (ROOT / name).is_file():
            yield ROOT / name
    for top in SCAN_DIRS:
        base = ROOT / top
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            rel = path.relative_to(ROOT)
            if SKIP_PARTS.intersection(rel.parts) or not path.is_file() or path == SELF:
                continue
            if path.suffix in TEXT_SUFFIXES or path.name == "Dockerfile":
                yield path


def _component(rel: str) -> str:
    if "/tests/" in rel or rel.startswith(("tests/", "conformance/")):
        return "tests"
    return next((name for prefix, name in COMPONENTS if rel.startswith(prefix)), "other")


def environment_variables() -> dict[str, set[str]]:
    """Every configuration variable in the source tree, with the components that mention it."""
    found: dict[str, set[str]] = {}
    for path in _source_files():
        try:
            text = path.read_text("utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        rel = path.relative_to(ROOT).as_posix()
        for name in set(_VAR.findall(text)):
            if name in NOT_CONFIGURATION or _DEV_CMD.fullmatch(name):
                continue
            found.setdefault(name, set()).add(_component(rel))
    try:
        from mapi_server.settings import Settings

        for field in Settings.model_fields:
            found.setdefault(f"MAPI_{field.upper()}", set()).add("mapi-server")
    except ImportError:  # pragma: no cover - the docs environment installs every package
        pass
    return found


def _config_sections() -> dict[str, tuple[str, str]]:
    """Variable -> (heading, anchor) of the configuration-reference section naming it first."""
    from markdown.extensions.toc import slugify

    sections: dict[str, tuple[str, str]] = {}
    heading: tuple[str, str] | None = None  # the introduction only names variables in passing
    for line in CONFIG_PAGE.read_text("utf-8").splitlines():
        if line.startswith("## "):
            text = line[3:].strip()
            plain = text.replace("`", "")
            heading = (plain, slugify(plain, "-"))
            continue
        if heading is None:
            continue
        for name in re.findall(r"`(MAPI_[A-Z0-9_]+)`", line):
            sections.setdefault(name, heading)
    return sections


def environment_page() -> str:
    found = environment_variables()
    sections = _config_sections()
    rows = []
    for name in sorted(found):
        readers = ", ".join(sorted(found[name] - {"tests"}) or ["tests"])
        if name in sections:
            title, anchor = sections[name]
            where = f"[{title}](../../operations/configuration.md#{anchor})"
        else:
            where = NOT_READ.get(name, "—")
        rows.append(f"| `{name}` | {readers} | {where} |")
    return (
        HEADER
        + "# Environment variables\n\n"
        + f"Every one of the {len(found)} `MAPI_*` variables in the source tree, generated by "
        + "`scripts/gen_docs_platform.py` from a scan of the code, the images, the Terraform "
        + "and the deploy scripts, with the components that mention it and the section of the "
        + "[configuration reference](../../operations/configuration.md) that explains it. "
        + "Server settings also have their own [generated table](server-settings.md). A test "
        + "fails when a variable is missing from the configuration reference.\n\n"
        + "| Variable | Mentioned by | Explained in |\n|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )


# ---------------------------------------------------------------------------------- driver

PAGES = {"permissions.md": permissions_page, "environment-variables.md": environment_page}
FRAGMENT_MAKERS = {
    "roles-matrix": roles_matrix,
    "token-scopes": scopes_matrix,
    "capabilities": capabilities_table,
    "trust-tiers": trust_tiers,
    "metrics": metrics_table,
    "alerts": alerts_table,
    "dashboards": dashboards_table,
    "runbooks": runbooks_table,
}


def fragment_names() -> Iterable[str]:
    return FRAGMENT_MAKERS.keys()


def generate(out: Path = OUT) -> list[Path]:
    """Write every page and fragment; return the files that changed."""
    changed: list[Path] = []
    for name, make in PAGES.items():
        if _write(out / name, make()):
            changed.append(out / name)
    for name, make_fragment in FRAGMENT_MAKERS.items():
        path = out / FRAGMENTS / f"{name}.md"
        if _write(path, make_fragment()):
            changed.append(path)
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    for path in generate(args.out):
        print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
