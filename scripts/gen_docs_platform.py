def _matrix_rows() -> Iterator[tuple[str, str, Any]]:
    """Every (resource, action) rule, the actions of one resource together, in the order the
    resources first appear in the matrix (so later additions such as M3.5's ``model``
    actions join their resource's rows)."""
    from mapi_spec.tenancy import PERMISSIONS

    first: dict[str, int] = {}
    for resource, _ in PERMISSIONS:
        first.setdefault(resource.value, len(first))
    rows = [(r.value, a.value, rule) for (r, a), rule in PERMISSIONS.items()]
    yield from sorted(rows, key=lambda row: first[row[0]])  # stable: actions keep their order


def roles_matrix() -> str:
    """Role x permission table: one row per (resource, action)."""
    from mapi_spec.tenancy import (
        OPERATOR_PERMISSIONS,
        Action,
        Level,
        ProjectRole,
        ResourceKind,
        can,
    )

    roles = list(ProjectRole)
    lines = [
        "| Resource | Action | " + " | ".join(f"`{r.value}`" for r in roles) + " | Operator |",
        "|---|---|" + "---|" * len(roles) + "---|",
    ]
    previous = None
    for resource, action, rule in _matrix_rows():
        label = f"`{resource}`" if resource != previous else ""
        previous = resource
        note = ACTION_NOTES.get((resource, action))
        act = f"{action} ({note})" if note else action
        if rule.level is Level.INTERNAL:
            cells = ["—"] * len(roles)
            op = "internal services only"
        else:
            suffix = " tenant-wide" if rule.level is Level.TENANT else ""
            cells = []
            for r in roles:
                if can(r, action, resource):
                    cells.append(YES + suffix)
                elif rule.capability is not None and can(r, action, resource, [rule.capability]):
                    cells.append(f"{YES} with `{rule.capability.value}`")
                else:
                    cells.append("")
            op = YES if (ResourceKind(resource), Action(action)) in OPERATOR_PERMISSIONS else ""
        lines.append(f"| {label} | {_cell(act)} | " + " | ".join(cells) + f" | {op} |")
    return "\n".join(lines) + "\n"


def _scope_columns() -> tuple[str, ...]:
    """Every scope family but ``admin`` (which covers everything); ``score`` as ``score:*``."""
    from mapi_spec.tokens import ScopeName

    return tuple(
        "score:*" if s is ScopeName.SCORE else s.value
        for s in ScopeName
        if s is not ScopeName.ADMIN
    )


SCOPE_COLUMNS = _scope_columns()

#: What each capability allows, in plain words. A test checks every ``Capability`` has one.
CAPABILITY_TEXT: dict[str, str] = {
    "reviewer": "Approve or reject model validations that wait for a second person "
    "(`POST /v1/validations/{id}/approvals`), never the member's own submissions "
    "(`SELF_APPROVAL_FORBIDDEN`) and never through an API token. Granted per project "
    "membership (`capabilities` on the membership, or the Reviewer column of Members); "
    "viewers cannot hold it.",
}


def capabilities_section() -> str:
    return (
        "A capability is granted on top of a role, per project membership; project admins hold "
        "every capability implicitly. A rule that needs one says so in the roles table "
        '("✓ with `reviewer`").\n\n' + capabilities_table()
    )


def capabilities_table() -> str:
    """Grants on top of a role (``mapi_spec.tenancy.Capability``) and the rules needing them."""
    from mapi_spec.tenancy import Capability

    lines = [
        "| Capability | Needed for | What it allows |",
        "|---|---|---|",
    ]
    for cap in Capability:
        needs = ", ".join(
            f"`{resource}` {action}"
            for resource, action, rule in _matrix_rows()
            if rule.capability is cap
        )
        lines.append(f"| `{cap.value}` | {needs} | {_cell(CAPABILITY_TEXT[cap.value])} |")
    return "\n".join(lines) + "\n"


def scopes_matrix() -> str:
    """Which token scope covers which (resource, action) (``admin`` covers everything)."""
    from mapi_spec.tenancy import Level
    from mapi_spec.tokens import scope_allows

    lines = [
        "| Resource | Action | " + " | ".join(f"`{s}`" for s in SCOPE_COLUMNS) + " |",
        "|---|---|" + "---|" * len(SCOPE_COLUMNS),
    ]
    previous = None
    for resource, action, rule in _matrix_rows():
        if rule.level is not Level.PROJECT:
            continue  # tenant, platform and internal rules are never reachable with a token
        cells = [YES if scope_allows([s], action, resource) else "" for s in SCOPE_COLUMNS]
        if not any(cells):
            continue
        label = f"`{resource}`" if resource != previous else ""
        previous = resource
        lines.append(f"| {label} | {action} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def _limit(value: object, unit: str = "") -> str:
    from mapi_spec.quotas import GIB

    if value is None:
        return "—"
    if unit == "bytes":
        return f"{int(value) // GIB:,} GiB"  # type: ignore[call-overload]
    if hasattr(value, "value"):
        return str(value.value)
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    return f"{value:,}" if isinstance(value, int) else str(value)


def trust_tiers() -> str:
    """Placement requirements and default quotas of each trust tier, and the global defaults."""
    from mapi_spec.quotas import DEFAULT_GLOBAL_LIMITS, DEFAULT_TIER_LIMITS
    from mapi_spec.tenancy import TIER_PLACEMENT

    head = (
        "| Tier | Executor must provide | vCPU-s / day | vCPU-s / month | Concurrent runs "
        "| Fan-out tasks | Largest class | Storage | Egress / month | Requests / min |\n"
        "|---|---|---|---|---|---|---|---|---|---|\n"
    )
    rows = []
    for tier, req in TIER_PLACEMENT.items():
        needs = f"isolation ≥ {req.min_isolation.name.lower()}"
        if req.egress_enforced or req.dns_enforced:
            needs += ", egress and DNS enforced"
        q = DEFAULT_TIER_LIMITS[tier]
        rows.append(
            f"| `{tier.value}` | {needs} | {_limit(q.vcpu_seconds_per_day)} "
            f"| {_limit(q.vcpu_seconds_per_month)} | {_limit(q.concurrent_runs)} "
            f"| {_limit(q.max_fanout_tasks)} | {_limit(q.max_resource_class)} "
            f"| {_limit(q.storage_bytes, 'bytes')} | {_limit(q.egress_bytes_per_month, 'bytes')} "
            f"| {_limit(q.requests_per_minute)} |"
        )
    glob = DEFAULT_GLOBAL_LIMITS
    set_fields = {k: v for k, v in glob.model_dump().items() if v is not None}
    tail = ", ".join(f"`{k}` = {_limit(v)}" for k, v in set_fields.items())
    return (
        head
        + "\n".join(rows)
        + f"\n\nPlatform-wide (`global`) defaults: {tail}. A dash means no limit at that level.\n"
    )


