"""Generate the multi-tenant and operations reference from the code and the ops/ files.

Writes into ``docs/reference/generated/`` (git-ignored):

* ``permissions.md``          - the whole permission matrix (``mapi_spec.tenancy.PERMISSIONS``),
  what operators may do, what each token scope covers (``mapi_spec.tokens.scope_allows``) and
  the trust tiers (``TIER_PLACEMENT``, ``DEFAULT_TIER_LIMITS``);
* ``environment-variables.md`` - every ``MAPI_*`` variable found in the source tree, who reads
  it and the section of the configuration reference that explains it;
* ``fragments/*.md``           - tables embedded into hand-written pages: the roles matrix, the
  token scopes and trust tiers (Administration guide); the metric set
  (``mapi_server.observability.metrics.Metrics``), the alerts (``ops/alerts``), the dashboards
  (``ops/dashboards``) and the runbooks (``ops/runbooks``) (Observability page).

A page embeds a fragment with a line ``<!-- generated: NAME -->``; the MkDocs hook in
``scripts/mkdocs_hooks.py`` replaces it before the page is rendered and fails the build when
the fragment does not exist. ``make docs-catalog`` runs this script, and the hook runs it before
every build. Files are only rewritten when their content changes.
"""

from __future__ import annotations

import argparse
import json
import re
from collections.abc import Iterable, Iterator, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "generated"
FRAGMENTS = "fragments"
CONFIG_PAGE = ROOT / "docs" / "operations" / "configuration.md"
SELF = Path(__file__).resolve()

HEADER = (
    "<!-- Generated by scripts/gen_docs_platform.py from the code. Do not edit by hand. -->\n\n"
)
YES = "✓"


def _write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text("utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, "utf-8")
    return True


def _cell(text: object) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


