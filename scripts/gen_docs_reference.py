"""Generate the platform reference pages from the code itself.

Writes into ``docs/reference/generated/`` (git-ignored):

* ``cli-reference.md``   - every ``mapi`` command's ``--help``, rendered by the CLI's own Typer
  app at a fixed width, so the page always matches the installed CLI;
* ``server-settings.md`` - every ``mapi_server.settings.Settings`` field: its ``MAPI_*``
  variable, type, default and description;
* ``openapi.json``       - a copy of the committed OpenAPI 3.1 document
  (``apps/web/openapi.json``) that the OpenAPI explorer page loads.

``make docs-build`` runs it (through ``make docs-catalog``), and the MkDocs hook in
``scripts/mkdocs_hooks.py`` runs it before every build. Files are only rewritten when their
content changes.
"""

from __future__ import annotations

import argparse
import shutil
from collections.abc import Iterator, Sequence
from enum import Enum
from pathlib import Path
from typing import Any, Literal, get_args, get_origin

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "generated"
OPENAPI = ROOT / "apps" / "web" / "openapi.json"
HELP_WIDTH = 96

HEADER = (
    "<!-- Generated by scripts/gen_docs_reference.py from the installed packages. "
    "Do not edit by hand. -->\n\n"
)


def _write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text("utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, "utf-8")
    return True


# --------------------------------------------------------------------------------- CLI


def _commands(
    command: Any, path: tuple[str, ...], chain: tuple[Any, ...] = ()
) -> Iterator[tuple[tuple[str, ...], tuple[Any, ...]]]:
    """Every command below ``command`` (depth first, in listing order) with its parents.

    Duck-typed: Typer ships its own copy of click, so ``isinstance(x, click.Group)`` fails.
    """
    chain = (*chain, command)
    yield path, chain
    if hasattr(command, "list_commands"):
        ctx = command.context_class(command, info_name=path[-1])
        for name in command.list_commands(ctx):
            sub = command.get_command(ctx, name)
            if sub is not None and not getattr(sub, "hidden", False):
                yield from _commands(sub, (*path, name), chain)


def command_help(path: Sequence[str], chain: Sequence[Any]) -> str:
    """``mapi … --help`` for the last command of ``chain``, as a terminal shows it."""
    ctx = None
    for name, command in zip(path, chain, strict=True):
        ctx = command.context_class(
            command,
            info_name=name,
            parent=ctx,
            terminal_width=HELP_WIDTH,
            max_content_width=HELP_WIDTH,
            help_option_names=["-h", "--help"],
        )
    assert ctx is not None
    return str(chain[-1].get_help(ctx)).rstrip()


def cli_page() -> str:
    import typer
    from mapi_cli.main import app

    root = typer.main.get_command(app)
    entries = list(_commands(root, ("mapi",)))
    lines = [
        HEADER,
        "# CLI reference\n\n",
        "Every `mapi` command with its `--help`, generated from the installed CLI by "
        "`scripts/gen_docs_reference.py`. The [command-line guide](../../guides/cli.md) shows "
        "them in use. Global options (`--url`, `--token`, `--profile`, `--json`) go *before* "
        "the command: `mapi --json runs ls`.\n\n",
        "| Command | What it does |\n|---|---|\n",
    ]
    for path, chain in entries[1:]:
        anchor = "-".join(path)
        first = (chain[-1].help or "").strip().split("\n\n")[0]
        summary = " ".join(first.split()).replace("|", "\\|")
        lines.append(f"| [`{' '.join(path)}`](#{anchor}) | {summary} |\n")
    for path, chain in entries:
        anchor = "-".join(path)
        level = "##" if len(path) <= 2 else "###"
        lines.append(f"\n{level} `{' '.join(path)}` {{ #{anchor} }}\n\n")
        lines.append("```text\n" + command_help(path, chain) + "\n```\n")
    return "".join(lines)


# ------------------------------------------------------------------------- server settings


def _type_name(annotation: Any) -> str:
    if get_origin(annotation) is Literal:
        return " \\| ".join(f"`{a}`" for a in get_args(annotation))
    text = getattr(annotation, "__name__", None) or str(annotation)
    text = text.replace("typing.", "").replace("pathlib.", "").replace("mapi_server.settings.", "")
    if isinstance(annotation, type) and issubclass(annotation, Enum):
        return " \\| ".join(f"`{m.value}`" for m in annotation)
    return f"`{text}`".replace("|", "\\|")


def _default(field: Any) -> str:
    if field.default_factory is not None:
        return "(computed)"
    value = field.default
    if value is None:
        return "unset"
    if isinstance(value, Enum):
        value = value.value
    if isinstance(value, Path):
        value = str(value)
    return f"`{value}`"


def settings_page() -> str:
    from mapi_server.settings import Settings

    rows = []
    for name, field in Settings.model_fields.items():
        env = f"`MAPI_{name.upper()}`"
        alias = getattr(field.validation_alias, "choices", None)
        if alias:
            env = " or ".join(f"`{a}`" for a in alias if isinstance(a, str) and a.isupper())
        desc = (field.description or "").replace("|", "\\|")
        rows.append(f"| {env} | {_type_name(field.annotation)} | {_default(field)} | {desc} |")
    return (
        HEADER
        + "# Server settings\n\n"
        + "Every setting of `mapi-server` (`api`, `worker`, `migrate`, `dev`), generated from "
        + "`mapi_server.settings.Settings` by `scripts/gen_docs_reference.py`. Each field reads "
        + "the environment variable `MAPI_<FIELD>`; `.env` files are not read. The "
        + "[configuration reference](../../operations/configuration.md) explains them by task "
        + "and lists the variables of the other components.\n\n"
        + "| Variable | Type | Default | Description |\n|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )


# ---------------------------------------------------------------------------------- driver

PAGES = {"cli-reference.md": cli_page, "server-settings.md": settings_page}


def generate(out: Path = OUT) -> list[Path]:
    """Write every page and the OpenAPI copy; return the files that changed."""
    changed: list[Path] = []
    for name, make in PAGES.items():
        if _write(out / name, make()):
            changed.append(out / name)
    target = out / "openapi.json"
    if not target.exists() or target.read_bytes() != OPENAPI.read_bytes():
        out.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(OPENAPI, target)
        changed.append(target)
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    for path in generate(args.out):
        print(f"wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
