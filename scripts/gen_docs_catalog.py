"""Generate the documentation's reference pages from the live catalogs.

Writes Markdown (and the exported JSON Schemas) into ``docs/reference/generated/``:

* ``steps-catalog.md``  - every built-in step and split (``mapi_steps`` catalog export);
* ``models-catalog.md`` - every installed model plugin's manifest (``mapi.models`` entry points);
* ``plots-catalog.md``  - every installed plot recipe (``mapi.plots`` entry points);
* ``spec-schema.md``    - ModelSpec and ScoreRequest field tables (``mapi_spec.export_schemas``);
* ``error-codes.md``    - every stable error code (``mapi_spec.ERROR_INFO``);
* ``schemas/*.json``    - the JSON Schemas themselves, served next to the pages.

Run ``python scripts/gen_docs_catalog.py`` (``make docs-build`` does). The MkDocs hook in
``scripts/mkdocs_hooks.py`` runs it before every build, so ``mkdocs build`` alone also works.
Files are only rewritten when their content changes (no rebuild loops under ``mkdocs serve``).
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "generated"

HEADER = (
    "<!-- Generated by scripts/gen_docs_catalog.py from the installed packages. "
    "Do not edit by hand. -->\n\n"
)


# ----------------------------------------------------------------------------- helpers


def _cell(text: Any) -> str:
    """Make ``text`` safe inside a Markdown table cell."""
    s = str(text).replace("\n", " ").strip()
    return s.replace("|", "\\|")


def _code(value: Any, limit: int = 60) -> str:
    text = value if isinstance(value, str) else json.dumps(value, separators=(", ", ": "))
    if len(text) > limit:
        text = text[: limit - 1] + "…"
    return "`" + text.replace("`", "'") + "`"


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_str(s: Mapping[str, Any], link: bool = False) -> str:
    """A compact, human-readable type for a JSON Schema node."""
    if "$ref" in s:
        name = _ref_name(s["$ref"])
        return f"[`{name}`](#def-{name.lower()})" if link else f"`{name}`"
    if "const" in s:
        return _code(s["const"])
    if "enum" in s:
        return " or ".join(_code(v, 30) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = [p for p in s[key] if p.get("type") != "null"]
            nullable = len(parts) < len(s[key])
            text = " or ".join(type_str(p, link) for p in parts) or "`null`"
            return text + (" (optional)" if nullable else "")
    t = s.get("type")
    if t == "array":
        return f"list of {type_str(s.get('items', {}), link)}"
    if t == "object":
        if isinstance(s.get("additionalProperties"), dict):
            return f"map of {type_str(s['additionalProperties'], link)}"
        pattern = s.get("patternProperties")
        if isinstance(pattern, dict) and pattern:
            return f"map of {type_str(next(iter(pattern.values())), link)}"
        return "`object`"
    if isinstance(t, list):
        return " or ".join(f"`{x}`" for x in t)
    return f"`{t}`" if t else "any"


def _constraints(s: Mapping[str, Any]) -> list[str]:
    out = []
    for key, word in (
        ("minimum", "≥"),
        ("exclusiveMinimum", ">"),
        ("maximum", "≤"),
        ("exclusiveMaximum", "<"),
    ):
        if key in s:
            out.append(f"{word} {s[key]}")
    for key, word in (("minItems", "min items"), ("maxItems", "max items")):
        if key in s:
            out.append(f"{word} {s[key]}")
    return out


def properties_table(
    schema: Mapping[str, Any], *, link: bool = False, ui_level: bool = False
) -> str:
    """A Markdown table of an object schema's properties."""
    props: Mapping[str, Any] = schema.get("properties", {})
    if not props:
        return "_No settings._\n"
    required = set(schema.get("required", []))
    head = "| Field | Type | Default | Description |\n|---|---|---|---|\n"
    if ui_level:
        head = "| Field | Type | Default | Level | Description |\n|---|---|---|---|---|\n"
    rows = []
    for name, p in props.items():
        default = (
            "**required**" if name in required else (_code(p["default"]) if "default" in p else "–")
        )
        desc = p.get("description") or ""
        extra = _constraints(p)
        if extra:
            desc = f"{desc} ({', '.join(extra)})" if desc else ", ".join(extra)
        cells = [f"`{name}`", type_str(p, link), default]
        if ui_level:
            cells.append(str(p.get("x-ui-level", "–")))
        cells.append(_cell(desc))
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n".join(rows) + "\n"


def _defs_section(schema: Mapping[str, Any], *, heading: str = "###") -> str:
    parts = []
    for name, d in sorted(schema.get("$defs", {}).items()):
        parts.append(f"{heading} `{name}` {{#def-{name.lower()}}}\n")
        if d.get("description"):
            parts.append(_cell(d["description"]) + "\n")
        if "enum" in d:
            parts.append("One of " + ", ".join(_code(v, 40) for v in d["enum"]) + ".\n")
        elif "properties" in d:
            parts.append(properties_table(d, link=True))
        else:
            parts.append(f"Type: {type_str(d, link=True)}\n")
    return "\n".join(parts)


def _json_block(value: Any, title: str) -> str:
    body = json.dumps(value, indent=2, sort_keys=False)
    indented = "\n".join("    " + line for line in body.splitlines())
    return f'??? note "{title}"\n\n    ```json\n{indented}\n    ```\n'


def _yes(flag: bool) -> str:
    return "yes" if flag else "–"


# ----------------------------------------------------------------------------- pages


def steps_page() -> str:
    from mapi_steps.catalog import catalog
    from mapi_steps.splits import split_catalog

    steps = sorted(catalog().steps, key=lambda e: (e.kind.value, e.id))
    lines = [
        HEADER,
        "# Built-in steps catalog\n",
        "Generated from the `mapi-steps` catalog export (`python -m mapi_steps.catalog`): the same",
        "static JSON the control plane uses to validate specs without importing step code. For",
        "how the steps behave together, read [Built-in steps](../steps.md).\n",
        "| Step | Kind | Learns state | Invertible | Looks back | Summary |",
        "|---|---|---|---|---|---|",
    ]
    for e in steps:
        anchor = e.id.replace(".", "-")
        lines.append(
            f"| [`{e.id}`](#{anchor}) | {e.kind.value} | {_yes(e.stateful)} | "
            f"{_yes(e.invertible)} | {_yes(e.context is not None)} | {_cell(e.summary or '')} |"
        )
    lines.append("")
    for e in steps:
        anchor = e.id.replace(".", "-")
        lines.append(f"## `{e.id}` {{#{anchor}}}\n")
        if e.summary_plain:
            lines.append(f"*{_cell(e.summary_plain)}*\n")
        facts = [f"version `{e.version}`", f"kind **{e.kind.value}**"]
        if e.stateful:
            facts.append("learns state on the training data")
        if e.invertible:
            facts.append("invertible")
        if e.depends_on_target:
            facts.append("depends on the target (recursive at forecast time)")
        if e.side_table_params:
            facts.append(
                "reads side tables via " + ", ".join(f"`{p}`" for p in e.side_table_params)
            )
        lines.append(" · ".join(facts) + "\n")
        lines.append(
            f"```yaml\n- {{id: my_{e.id.split('.')[-1]}, use: {e.id}@^1, with: {{...}}}}\n```\n"
        )
        lines.append(properties_table(e.settings_schema, link=False))
        if e.context is not None:
            lines.append(f"**Context need** (per group, stored at fit): {_code(e.context, 200)}\n")
        if e.effect:
            lines.append(_json_block(e.effect, "Schema effect template"))
    lines.append("## Splits {#splits}\n")
    lines.append("The `data.split.kind` values. Each has its own settings.\n")
    for sp in split_catalog():
        lines.append(f"### `{sp.kind}` {{#split-{sp.kind.replace('_', '-')}}}\n")
        if sp.summary:
            lines.append(_cell(sp.summary) + "\n")
        if sp.summary_plain:
            lines.append(f"*{_cell(sp.summary_plain)}*\n")
        schema = dict(sp.settings_schema)
        schema["properties"] = {
            k: v for k, v in schema.get("properties", {}).items() if k != "kind"
        }
        lines.append(properties_table(schema))
    return "\n".join(lines)


def models_page() -> str:
    from mapi_sdk import default_registry

    entries = sorted(default_registry().catalog().models, key=lambda e: e.id)
    lines = [
        HEADER,
        "# Built-in models catalog\n",
        "Generated from the manifests of every model plugin installed through the `mapi.models`",
        "entry point. Read [Built-in models](../models.md) for how to use them.\n",
        "| Model | Version | Inference | Representation | Score modes |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        caps = e.manifest.capabilities
        lines.append(
            f"| [`{e.id}`](#{e.id.replace('.', '-')}) | `{e.version}` | {caps.inference} | "
            f"{caps.representation.value} | {', '.join(sorted(caps.score_modes))} |"
        )
    lines.append("")
    for e in entries:
        m = e.manifest
        caps = m.capabilities
        lines.append(f"## `{m.id}` {{#{m.id.replace('.', '-')}}}\n")
        if m.description:
            lines.append(_cell(m.description) + "\n")
        facts = [
            ("Version", f"`{m.version}`"),
            ("Inference", caps.inference),
            ("Representation", f"`{caps.representation.value}`"),
            ("Score modes", ", ".join(f"`{x}`" for x in sorted(caps.score_modes))),
            ("Contributions", caps.contribution_scale),
            ("Decision objective", _yes(caps.decision)),
            ("Fast scoring", _yes(caps.fast_score)),
            ("Owns", ", ".join(sorted(caps.owns)) or "–"),
            ("LOO", "valid" if caps.loo_valid else f"invalid: {caps.loo_invalid_reason}"),
            ("Default plots", ", ".join(f"`{p}`" for p in m.plots) or "–"),
            (
                "Resources",
                f"class {m.resources.default_class.name} (min {m.resources.min_class.name})",
            ),
        ]
        lines.append("| | |\n|---|---|")
        lines.extend(f"| {k} | {_cell(v)} |" for k, v in facts)
        lines.append("")
        if m.outputs:
            lines.append(
                "**Outputs**\n\n| Output | Dims | Units | Description |\n|---|---|---|---|"
            )
            for name, o in m.outputs.items():
                units = f"of `{o.units_of}`" if o.units_of else (o.units or "–")
                lines.append(
                    f"| `{name}` | ({', '.join(o.dims)}) | {units} | {_cell(o.description or '')} |"
                )
            lines.append("")
        if m.derived:
            lines.append(
                "**Derived quantities** (`outputs.derived`)\n\n"
                "| Name | Dims | Units | Cached | Description |\n|---|---|---|---|---|"
            )
            for d in m.derived:
                lines.append(
                    f"| `{d.name}` | ({', '.join(d.dims)}) | {d.units or '–'} | {d.cache} | "
                    f"{_cell(d.description or '')} |"
                )
            lines.append("")
        lines.append("**Settings** (`model.settings`)\n")
        lines.append(properties_table(m.settings_schema, ui_level=True))
        if m.settings_schema.get("$defs"):
            nested = _defs_section(m.settings_schema, heading="####")
            nested = nested.replace("{#def-", "{#" + m.id.replace(".", "-") + "-def-")
            nested = nested.replace("](#def-", "](#" + m.id.replace(".", "-") + "-def-")
            lines.append('??? info "Nested settings types"\n')
            lines.extend("    " + ln if ln else "" for ln in nested.splitlines())
            lines.append("")
        lines.append(
            _json_block(
                m.schema_template.model_dump(mode="json", exclude_defaults=True),
                "Input data contract (schema template)",
            )
        )
    return "\n".join(lines)


def plots_page() -> str:
    from mapi_sdk import default_registry

    entries = sorted(default_registry().catalog().plots, key=lambda e: e.id)
    lines = [
        HEADER,
        "# Plot recipes catalog\n",
        "Generated from every recipe installed through the `mapi.plots` entry point. Name them",
        "in a spec's `outputs.plots`. See [Plots](../../guides/plots.md) for what each shows.\n",
        "| Recipe | Version | Title | Persona | Needs groups | Needs representation |",
        "|---|---|---|---|---|---|",
    ]
    for p in entries:
        groups = ", ".join(f"`{g}`" for g in p.requires_groups) or "–"
        reps = ", ".join(r.value for r in p.requires_representation) or "any"
        lines.append(
            f"| `{p.id}` | `{p.version}` | {_cell(p.title)} | {p.persona} | {groups} | {reps} |"
        )
    return "\n".join(lines) + "\n"


def spec_page(schemas: Mapping[str, Mapping[str, Any]]) -> str:
    lines = [
        HEADER,
        "# Spec schema reference\n",
        "Field-by-field reference for the two documents most people write, generated from",
        "`mapi_spec.export_schemas()` (JSON Schema 2020-12). Unknown fields are rejected",
        'everywhere (`extra="forbid"`). Read [Spec format](../spec-format.md) for the prose',
        "version with examples.\n",
        '!!! tip "Validate as you type"',
        "    Point your editor's YAML language server at the schema files below, for example",
        "    with a `# yaml-language-server: $schema=modelspec.json` comment.\n",
        "| Schema | Download |",
        "|---|---|",
    ]
    for name in sorted(schemas):
        lines.append(f"| `{schemas[name].get('title', name)}` | [{name}](schemas/{name}) |")
    lines.append("")
    for name, title in (("modelspec.json", "ModelSpec"), ("scorerequest.json", "ScoreRequest")):
        s = schemas[name]
        lines.append(f"## `{title}` {{#{title.lower()}}}\n")
        if s.get("description"):
            lines.append(_cell(s["description"]) + "\n")
        lines.append(properties_table(s, link=True))
        lines.append(_defs_section(s))
    return "\n".join(lines)


def errors_page() -> str:
    from mapi_spec import ERROR_INFO

    lines = [
        HEADER,
        "# Error codes\n",
        "Every error is a `MapiError` with one of these stable codes. Over HTTP it becomes an",
        "RFC 7807 problem document (`application/problem+json`) whose `type` ends in the code.",
        "Anything your data or a plugin said is returned separately, as `untrusted_text`.\n",
    ]
    by_cat: dict[str, list[tuple[str, Any]]] = {}
    for code, info in ERROR_INFO.items():
        by_cat.setdefault(info.category, []).append((code.value, info))
    titles = {
        "spec": "Spec and static validation",
        "coords": "Score-time coordinate checks (CoordPlan)",
        "capability": "Capabilities",
        "quota": "Quotas",
        "api": "API",
        "run": "Run failures",
        "internal": "Internal",
    }
    for cat, items in by_cat.items():
        lines.append(f"## {titles.get(cat, cat)}\n")
        lines.append("| Code | HTTP | Meaning | Retryable |\n|---|---|---|---|")
        for code, info in items:
            lines.append(
                f"| `{code}` | {info.status} | {_cell(info.title)} | {_yes(info.retryable)} |"
            )
        lines.append("")
    return "\n".join(lines)


# ----------------------------------------------------------------------------- driver


def _write(path: Path, text: str) -> bool:
    """Write ``text`` if it differs from what is on disk; return whether it changed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text("utf-8") == text:
        return False
    path.write_text(text, "utf-8")
    return True


def generate(out: Path = OUT, *, only: Iterable[str] | None = None) -> list[Path]:
    """Generate every page into ``out``; returns the files that changed."""
    from mapi_spec import export_schemas

    wanted = set(only) if only is not None else None
    schemas = export_schemas()
    pages: dict[str, Any] = {
        "steps-catalog.md": steps_page,
        "models-catalog.md": models_page,
        "plots-catalog.md": plots_page,
        "spec-schema.md": lambda: spec_page(schemas),
        "error-codes.md": errors_page,
    }
    changed = []
    for name, make in pages.items():
        if wanted is not None and name not in wanted:
            continue
        if _write(out / name, make()):
            changed.append(out / name)
    if wanted is None or "schemas" in wanted:
        for name, schema in schemas.items():
            text = json.dumps(schema, indent=2, sort_keys=True) + "\n"
            if _write(out / "schemas" / name, text):
                changed.append(out / "schemas" / name)
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=OUT, help="output directory")
    args = parser.parse_args(argv)
    changed = generate(args.out)
    print(f"gen_docs_catalog: {len(changed)} file(s) updated in {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
